#!/usr/bin/env python3
"""Turns gen's text output into a C++ include: byte arrays and expected values."""
import sys
frames, sync, lines = [], [], []
for line in open(sys.argv[1]):
    parts = line.split()
    if not parts: continue
    tag = parts[0]
    if tag in ('PSF','MIF','DATA','PSF2','MIF2','PSF3','DATA2','MIF4','PSF5','ETH'):
        n, hx = int(parts[1]), parts[2]
        body = ','.join('0x'+hx[i:i+2] for i in range(0, 2*n, 2))
        frames.append(f'static const uint8_t v_{tag.lower()}[{n}]={{{body}}};')
    elif tag == 'SYNC':
        sync.append('{%s,%s,%s,%s,%s,%s,%d}' % (parts[1], parts[3], parts[5], parts[7], parts[9], parts[11], round(float(parts[13])*1e6)))
    else:
        lines.append(line.rstrip('\n'))
print('// Generated by awdl-vectors/generate.sh from OWL\'s C code; do not edit.')
print('\n'.join(frames))
print('struct SyncVector{uint64_t now;uint16_t nextAwTu;uint64_t nextAwUs;uint16_t curAw;uint16_t curEaw;int mcast;int64_t canSend16Us;};')
print('static const SyncVector v_sync[]={' + ','.join(sync) + '};')
for l in lines:
    p = l.split()
    key = p[0]
    print(f'// {l}')
    if key == 'PEER' and p[1] == 'valid':
        print(f'static const int e_peer_valid={p[2]};static const char *e_peer_name="{p[4]}";static const unsigned e_peer_ver={p[6]},e_peer_devclass={p[8]},e_peer_v2={p[10]},e_peer_height={p[12]},e_peer_master_metric={p[14]},e_peer_self_metric={p[16]},e_peer_master_counter={p[18]},e_peer_self_counter={p[20]};static const uint64_t e_peer_last_update={p[22]};')
    if key == 'PEER' and p[1] == 'master':
        print(f'static const char *e_peer_master="{p[2]}",*e_peer_sync="{p[4]}";static const unsigned e_peer_seq[16]={{{",".join(p[6:22])}}};')
    if key == 'ELECT':
        print(f'static const char *e_elect_master="{p[2]}";static const unsigned e_elect_height={p[4]},e_elect_metric={p[6]},e_elect_counter={p[8]};')
    if key == 'ELECT2':
        print(f'static const char *e_elect2_master="{p[2]}",*e_elect2_sync="{p[4]}";static const unsigned e_elect2_height={p[6]},e_elect2_metric={p[8]},e_elect2_counter={p[10]};')
    if key == 'RSYNC':
        print(f'static const uint64_t e_rsync_last_update={p[2]};static const unsigned e_rsync_aw_counter={p[4]};')
    if key == 'RSYNC2':
        print(f'static const uint64_t e_rsync2_last_update={p[2]};static const unsigned e_rsync2_aw_counter={p[4]},e_rsync2_err={p[6]},e_rsync2_total={p[8]};')
    if key == 'RSYNCT':
        print(f'static const struct{{uint64_t now;unsigned nextAwTu,curEaw;int sameChan;}} e_rsynct_{p[1]}={{{p[1]},{p[3]},{p[5]},{p[7]}}};')
    if key.startswith('RX_'):
        print(f'static const int e_{key.lower()}={p[1]};')
