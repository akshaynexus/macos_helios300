// ---------------------------------------------------------------- small helpers
inline uint64_t tuToUs(uint64_t tu) { return tu * 1024; }
inline uint64_t usToTu(uint64_t us) { return us / 1024; }
inline uint8_t version(int major, int minor) { return uint8_t(((major << 4) & 0xf0) | (minor & 0x0f)); }
inline int versionMajor(uint8_t v) { return (v >> 4) & 0xf; }
inline int versionMinor(uint8_t v) { return v & 0xf; }
inline void put16le(uint8_t *p, uint16_t v) { p[0] = uint8_t(v); p[1] = uint8_t(v >> 8); }
inline void put32le(uint8_t *p, uint32_t v) { for (int i = 0; i < 4; ++i) p[i] = uint8_t(v >> (8 * i)); }
inline void put16be(uint8_t *p, uint16_t v) { p[0] = uint8_t(v >> 8); p[1] = uint8_t(v); }
inline uint16_t get16le(const uint8_t *p) { return uint16_t(p[0] | (p[1] << 8)); }
inline uint32_t get32le(const uint8_t *p) { return uint32_t(p[0]) | (uint32_t(p[1]) << 8) | (uint32_t(p[2]) << 16) | (uint32_t(p[3]) << 24); }
inline uint16_t get16be(const uint8_t *p) { return uint16_t((p[0] << 8) | p[1]); }

struct Addr {
    uint8_t b[6];
    bool operator==(const Addr &o) const { return memcmp(b, o.b, 6) == 0; }
    bool operator!=(const Addr &o) const { return !(*this == o); }
    bool multicast() const { return b[0] & 1; }
    static Addr of(const uint8_t *p) { Addr a; memcpy(a.b, p, 6); return a; }
};
inline int compareAddr(const Addr &a, const Addr &b) { return memcmp(a.b, b.b, 6); }

// Bounded reader over an immutable byte range (OWL's struct buf, read side).
struct Reader {
    const uint8_t *data; size_t len;
    Reader(const uint8_t *d, size_t n) : data(d), len(n) {}
    bool has(size_t off, size_t n) const { return off <= len && n <= len - off; }
    bool u8(size_t off, uint8_t *v) const { if (!has(off, 1)) return false; if (v) *v = data[off]; return true; }
    bool le16(size_t off, uint16_t *v) const { if (!has(off, 2)) return false; if (v) *v = get16le(data + off); return true; }
    bool be16(size_t off, uint16_t *v) const { if (!has(off, 2)) return false; if (v) *v = get16be(data + off); return true; }
    bool le32(size_t off, uint32_t *v) const { if (!has(off, 4)) return false; if (v) *v = get32le(data + off); return true; }
    bool addr(size_t off, Addr *v) const { if (!has(off, 6)) return false; if (v) memcpy(v->b, data + off, 6); return true; }
    bool bytes(size_t off, uint8_t *v, size_t n) const { if (!has(off, n)) return false; if (v) memcpy(v, data + off, n); return true; }
    bool strip(size_t n) { if (n > len) return false; data += n; len -= n; return true; }
    bool take(size_t n) { if (n > len) return false; len -= n; return true; }
    // <len><bytes> string; copies at most max bytes and terminates.
    bool intString(size_t off, char *s, size_t max, size_t *consumed) const {
        uint8_t n; if (!u8(off, &n)) return false;
        size_t copy = n > max ? max : n;
        if (!has(off + 1, n)) return false;
        memcpy(s, data + off + 1, copy); s[copy] = 0;
        if (consumed) *consumed = size_t(n) + 1;
        return true;
    }
    // AWDL TLV: type u8, length le16, value.
    bool tlv(size_t off, uint8_t *type, uint16_t *n, const uint8_t **val) const {
        uint8_t t; uint16_t l;
        if (!u8(off, &t) || !le16(off + 1, &l) || !has(off + 3, l)) return false;
        if (type) *type = t;
        if (n) *n = l;
        if (val) *val = data + off + 3;
        return true;
    }
};

// ---------------------------------------------------------------- channels
struct Chan {
    uint8_t val[2]; // simple: {num}; legacy: {flags,num}; opclass: {num,opclass}
    static Chan null() { return Chan{{0, 0}}; }
    static Chan opclass6() { return Chan{{6, 0x51}}; }
    static Chan opclass44() { return Chan{{44, 0x80}}; }
    static Chan opclass149() { return Chan{{149, 0x80}}; }
    static Chan opclass(uint8_t num) { return num == 6 ? opclass6() : num == 44 ? opclass44() : num == 149 ? opclass149() : null(); }
    bool operator==(const Chan &o) const { return val[0] == o.val[0] && val[1] == o.val[1]; }
};
inline uint8_t chanNum(Chan c, uint8_t enc) {
    switch (enc) { case kChanEncSimple: return c.val[0]; case kChanEncLegacy: return c.val[1]; case kChanEncOpclass: return c.val[0]; default: return 0; }
}
inline int chanEncodingSize(uint8_t enc) { return enc == kChanEncSimple ? 1 : (enc == kChanEncLegacy || enc == kChanEncOpclass) ? 2 : -1; }
inline int channelToFrequency(int chan) {
    if (chan <= 0) return 0;
    if (chan == 14) return 2484;
    if (chan < 14) return 2407 + chan * 5;
    if (chan < 32) return 0;
    if (chan >= 182 && chan <= 196) return 4000 + chan * 5;
    return 5000 + chan * 5;
}
inline void chanseqInitStatic(Chan *seq, Chan c) { for (int i = 0; i < kChanSeqLength; ++i) seq[i] = c; }
inline void chanseqInitDefault(Chan *seq) { for (int i = 0; i < kChanSeqLength; ++i) seq[i] = i < 8 ? Chan::opclass149() : Chan::opclass6(); }
inline void chanseqInitIdle(Chan *seq) {
    for (int i = 0; i < kChanSeqLength; ++i) seq[i] = (i == 8) ? Chan::opclass6() : (i == 0 || i == 9 || i == 10) ? Chan::opclass149() : Chan::null();
}
struct ChannelState { uint8_t enc; Chan sequence[kChanSeqLength]; Chan master; Chan current; };

// ---------------------------------------------------------------- synchronisation
struct SyncState {
    uint16_t awCounter; uint64_t lastUpdate; uint16_t awPeriod; uint8_t presenceMode; uint64_t measErr; uint64_t measTotal;
};
inline void syncInit(SyncState &s, uint64_t now) { s.lastUpdate = now; s.awCounter = 0; s.awPeriod = 16; s.presenceMode = 4; s.measErr = 0; s.measTotal = 0; }
inline uint16_t syncNextAwTu(uint64_t now, const SyncState &s) {
    uint64_t eaw = uint64_t(s.presenceMode) * s.awPeriod; uint64_t since = usToTu(now - s.lastUpdate); return uint16_t(eaw - (since % eaw));
}
inline uint64_t syncNextAwUs(uint64_t now, const SyncState &s) {
    uint64_t eaw = tuToUs(uint64_t(s.presenceMode) * s.awPeriod); uint64_t since = now - s.lastUpdate; return eaw - (since % eaw);
}
inline uint16_t syncCurrentAw(uint64_t now, const SyncState &s) {
    uint64_t eaw = uint64_t(s.presenceMode) * s.awPeriod; uint64_t since = usToTu(now - s.lastUpdate);
    return uint16_t(s.awCounter + (since % eaw) / s.awPeriod + s.presenceMode * (since / eaw));
}
inline uint16_t syncCurrentEaw(uint64_t now, const SyncState &s) { return uint16_t(syncCurrentAw(now, s) / s.presenceMode); }
inline int64_t syncErrorTu(uint64_t now, uint16_t timeToNextAw, uint16_t awCounter, const SyncState &s) {
    return (int64_t(awCounter / s.presenceMode) - int64_t(syncCurrentEaw(now, s))) * int64_t(s.presenceMode) * s.awPeriod
         - (int64_t(timeToNextAw) - int64_t(syncNextAwTu(now, s)));
}
inline void syncUpdateLast(uint64_t now, uint16_t timeToNextAw, uint16_t awCounter, SyncState &s) {
    uint64_t eaw = uint64_t(s.presenceMode) * s.awPeriod; s.lastUpdate = now - tuToUs(eaw - timeToNextAw); s.awCounter = awCounter & 0xfffc;
}

// ---------------------------------------------------------------- election
struct ElectionState {
    Addr masterAddr, syncAddr, selfAddr; uint32_t height, masterMetric, selfMetric, masterCounter, selfCounter;
};
inline bool electionIsSyncMaster(const ElectionState &s, const Addr &a) { return s.syncAddr == a; }
inline void electionResetSelf(ElectionState &s) { s.height = 0; s.masterAddr = s.selfAddr; s.syncAddr = s.selfAddr; s.masterMetric = s.selfMetric; s.masterCounter = s.selfCounter; }
inline void electionInit(ElectionState &s, const Addr &self) {
    s.masterAddr = s.syncAddr = s.selfAddr = self; s.selfCounter = kElectionCounterInit; s.selfMetric = kElectionMetricInit; electionResetSelf(s);
}
inline int compareU32(uint32_t a, uint32_t b) { return a < b ? -1 : (a > b); }
inline int electionCompareMaster(const ElectionState &a, const ElectionState &b) {
    int r = compareU32(a.masterCounter, b.masterCounter); if (!r) r = compareU32(a.masterMetric, b.masterMetric); return r;
}

// ---------------------------------------------------------------- peers
struct Peer {
    bool used; Addr addr; uint64_t lastUpdate; ElectionState election; uint8_t seqEnc; Chan sequence[kChanSeqLength];
    uint64_t syncOffset; char name[kHostNameMax + 1]; char countryCode[3]; Addr infraAddr; uint8_t version, devclass;
    bool supportsV2, sentMif, valid; int8_t rssi;
    bool isValidNow() const { return sentMif && devclass && version; }
};
enum PeersStatus { kPeersUpdate = 1, kPeersOk = 0, kPeersMissing = -1, kPeersFull = -2 };
struct PeerTable {
    Peer peers[kMaxPeers]; uint64_t timeout; uint64_t cleanInterval;
    void init() { memset(peers, 0, sizeof(peers)); timeout = kPeerTimeoutUs; cleanInterval = kPeerCleanIntervalUs; }
    int length() const { int n = 0; for (auto &p : peers) n += p.used; return n; }
    Peer *find(const Addr &a) { for (auto &p : peers) if (p.used && p.addr == a) return &p; return nullptr; }
    const Peer *find(const Addr &a) const { for (auto &p : peers) if (p.used && p.addr == a) return &p; return nullptr; }
    static void reset(Peer &p, const Addr &a) {
        memset(&p, 0, sizeof(p)); p.used = true; p.addr = a; electionInit(p.election, a); p.seqEnc = kChanEncOpclass;
        chanseqInitStatic(p.sequence, Chan::null()); p.countryCode[0] = 'N'; p.countryCode[1] = 'A'; p.countryCode[2] = 0;
    }
    // Adds or refreshes a peer; *becameValid is set when the peer passed validation for the first time.
    int add(const Addr &a, uint64_t now, Peer **out, bool *becameValid) {
        if (becameValid) *becameValid = false;
        Peer *p = find(a); int result = kPeersUpdate;
        if (!p) {
            for (auto &q : peers) if (!q.used) { p = &q; break; }
            if (!p) return kPeersFull;
            reset(*p, a); result = kPeersOk;
        }
        p->lastUpdate = now;
        if (!p->valid && p->isValidNow()) { p->valid = true; if (becameValid) *becameValid = true; }
        if (out) *out = p;
        return result;
    }
    int remove(const Addr &a, bool *wasValid) {
        Peer *p = find(a);
        if (!p) return kPeersMissing;
        if (wasValid) *wasValid = p->valid;
        p->used = false; return kPeersOk;
    }
};

// Election over the peer table (OWL awdl_election_run). Returns true when the top master or the sync master changed.
inline bool electionRun(ElectionState &state, const PeerTable &peers) {
    Addr oldTop = state.masterAddr, oldSync = state.syncAddr; const ElectionState *master = &state;
    electionResetSelf(state);
    for (auto &peer : peers.peers) {
        if (!peer.used || !peer.valid) continue;
        const ElectionState &ps = peer.election;
        if (ps.height + 1 > uint32_t(kElectionTreeMaxHeight)) continue;      // tree would get too large
        if (electionIsSyncMaster(ps, state.selfAddr)) continue;              // no cycles
        int cmp = electionCompareMaster(ps, *master);
        if (cmp < 0) continue;
        if (cmp == 0) {
            if (ps.height > master->height) continue;
            if (ps.height == master->height && compareAddr(ps.selfAddr, master->selfAddr) <= 0) continue;
        }
        master = &ps;
    }
    if (master != &state) {
        state.masterAddr = master->masterAddr; state.syncAddr = master->selfAddr; state.masterMetric = master->masterMetric;
        state.masterCounter = master->masterCounter; state.height = master->height + 1;
    }
    return oldTop != state.masterAddr || oldSync != state.syncAddr;
}

// ---------------------------------------------------------------- state
struct Stats { uint64_t txAction, txData, txDataUnicast, txDataMulticast, rxAction, rxData, rxUnknown; };
struct Ieee80211State { uint16_t sequenceNumber; uint16_t next() { uint16_t s = sequenceNumber; sequenceNumber = (sequenceNumber + 1) & 0x0fff; return s; } };
struct State {
    Addr self; char name[kHostNameMax + 1]; uint8_t version, devClass; uint16_t sequenceNumber, psfInterval; Addr dst;
    bool filterRssi; int8_t rssiThreshold, rssiGrace; ElectionState election; SyncState sync; ChannelState channel; PeerTable peers; Stats stats;
    uint16_t nextSequenceNumber() { return sequenceNumber++; }
};
inline void stateInit(State &s, const char *hostname, const Addr &self, Chan chan, uint64_t now) {
    memset(&s, 0, sizeof(s)); s.self = self;
    size_t n = strlen(hostname); if (n > kHostNameMax) n = kHostNameMax; memcpy(s.name, hostname, n); s.name[n] = 0;
    s.version = version(3, 4); s.devClass = kDevClassMacOS; s.sequenceNumber = 0; s.psfInterval = kPsfIntervalMasterTu;
    memcpy(s.dst.b, kBroadcast, 6); s.filterRssi = true; s.rssiThreshold = kRssiThresholdDefault; s.rssiGrace = kRssiGraceDefault;
    syncInit(s.sync, now); s.channel.enc = kChanEncOpclass; s.channel.master = chan; s.channel.current = Chan::null();
    chanseqInitStatic(s.channel.sequence, chan); electionInit(s.election, self); s.peers.init(); memset(&s.stats, 0, sizeof(s.stats));
}

// ---------------------------------------------------------------- schedule
inline bool sameChannelAsPeer(const State &s, uint64_t now, const Peer &peer) {
    int ownSlot = syncCurrentEaw(now, s.sync) % kChanSeqLength, peerSlot = syncCurrentEaw(now + peer.syncOffset, s.sync) % kChanSeqLength;
    int own = chanNum(s.channel.sequence[ownSlot], s.channel.enc), his = chanNum(peer.sequence[peerSlot], peer.seqEnc);
    return own && own == his;
}
inline bool isMulticastEaw(const State &s, uint64_t now) { int slot = syncCurrentEaw(now, s.sync) % kChanSeqLength; return slot == 0 || slot == 10; }
// 0: send now; >0: wait that many us; <0: inside the guard at the end of a slot, |value| us to the slot edge.
inline int64_t canSendIn(const State &s, uint64_t now, int guardTu) {
    uint64_t nextAw = syncNextAwUs(now, s.sync), guard = tuToUs(guardTu), eaw = tuToUs(64);
    if (nextAw < guard) return -int64_t(guard - nextAw);
    if (eaw - nextAw < guard) return int64_t(guard - (eaw - nextAw));
    return 0;
}
inline int64_t canSendUnicastIn(const State &s, const Peer &peer, uint64_t now, int guardTu) {
    uint64_t nextAw = syncNextAwUs(now, s.sync), guard = tuToUs(guardTu), eaw = tuToUs(64);
    if (!sameChannelAsPeer(s, now, peer)) return int64_t(nextAw);
    if (nextAw < guard) return sameChannelAsPeer(s, now + eaw, peer) ? 0 : -int64_t(guard - nextAw);
    if (eaw - nextAw < guard) return sameChannelAsPeer(s, now - eaw, peer) ? 0 : int64_t(guard - (eaw - nextAw));
    return 0;
}

// ---------------------------------------------------------------- receive
enum RxResult {
    kRxIgnorePeer = 6, kRxIgnoreRssi = 5, kRxIgnoreFromSelf = 2, kRxIgnore = 1, kRxOk = 0,
    kRxUnexpectedFormat = -1, kRxUnexpectedType = -2, kRxUnexpectedValue = -3, kRxTooShort = -4, kRxPeersFull = -5,
};
struct RxEvents {
    virtual void peerAdded(const Peer &) {}
    virtual void peerRemoved(const Peer &) {}
    virtual void syncChanged() {}
    virtual void tlv(const Peer &, uint8_t type, const uint8_t *val, uint16_t len) { (void)type; (void)val; (void)len; }
    virtual void data(const uint8_t *ethernet, size_t len, const Addr &src, const Addr &dst) { (void)ethernet; (void)len; (void)src; (void)dst; }
    virtual ~RxEvents() {}
};

inline int handleSyncParamsTlv(Peer &src, Reader v, State &s, uint64_t now, RxEvents *ev) {
    if (!electionIsSyncMaster(s.election, src.addr)) return kRxIgnore;
    uint16_t awCounterMaster, timeToNextAwMaster;
    if (!v.le16(1, &timeToNextAwMaster) || !v.le16(29, &awCounterMaster)) return kRxTooShort;
    s.sync.measTotal++;
    int64_t err = syncErrorTu(now, timeToNextAwMaster, awCounterMaster, s.sync);
    if (err > kSyncThresholdTu || err < -kSyncThresholdTu) s.sync.measErr++;
    syncUpdateLast(now, timeToNextAwMaster, awCounterMaster, s.sync);
    if (ev) ev->syncChanged();
    return kRxOk;
}
inline int handleChanSeqTlv(Peer &src, Reader v, State &s) {
    uint8_t count, encoding, duplicate, step; uint16_t fill;
    if (!v.u8(0, &count)) return kRxTooShort;
    if (count + 1 != kChanSeqLength) return kRxUnexpectedValue;
    if (!v.u8(2, &duplicate)) return kRxTooShort;
    if (duplicate) return kRxUnexpectedValue;
    if (!v.u8(3, &step)) return kRxTooShort;
    if (step + 1 != s.sync.presenceMode) return kRxUnexpectedValue;
    if (!v.le16(4, &fill)) return kRxTooShort;
    if (fill != 0xffff) return kRxUnexpectedValue;
    if (!v.u8(1, &encoding)) return kRxTooShort;
    int size = chanEncodingSize(encoding);
    if (size < 1) return kRxUnexpectedValue;
    Chan list[kChanSeqLength];
    for (int i = 0, off = 6; i < kChanSeqLength; ++i, off += size) {
        list[i] = Chan::null();
        if (!v.bytes(off, list[i].val, size)) return kRxTooShort;
    }
    memcpy(src.sequence, list, sizeof(list)); src.seqEnc = encoding; return kRxOk;
}
inline int handleElectionParamsTlv(Peer &src, Reader v) {
    if (src.supportsV2) return kRxOk;
    uint8_t distance;
    if (!v.u8(3, &distance) || !v.addr(5, &src.election.masterAddr) || !v.le32(11, &src.election.masterMetric) || !v.le32(15, &src.election.selfMetric)) return kRxTooShort;
    src.election.height = distance; return kRxOk;
}
inline int handleElectionParamsV2Tlv(Peer &src, Reader v) {
    if (!v.le32(16, &src.election.height) || !v.addr(0, &src.election.masterAddr) || !v.addr(6, &src.election.syncAddr) || !v.le32(12, &src.election.masterCounter) ||
        !v.le32(20, &src.election.masterMetric) || !v.le32(24, &src.election.selfMetric) || !v.le32(36, &src.election.selfCounter)) return kRxTooShort;
    src.supportsV2 = true; return kRxOk;
}
inline int handleArpaTlv(Peer &src, Reader v) { return v.intString(1, src.name, kHostNameMax, nullptr) ? kRxOk : kRxTooShort; }
inline int handleDataPathStateTlv(Peer &src, Reader v) {
    uint16_t flags; size_t off = 0;
    if (!v.le16(off, &flags)) return kRxTooShort;
    off += 2;
    if (flags & kDpCountryCode) { if (!v.bytes(off, (uint8_t *)src.countryCode, 3)) return kRxTooShort; off += 3; }
    if (flags & kDpSocialChannelMap) { if (!v.le16(off, nullptr)) return kRxTooShort; off += 2; }
    if (flags & kDpInfraInfo) {
        if (!v.addr(off, nullptr)) return kRxTooShort;
        off += 6;
        if (!v.le16(off, nullptr)) return kRxTooShort;
        off += 2;
    }
    if (flags & kDpInfraAddress) { if (!v.addr(off, &src.infraAddr)) return kRxTooShort; off += 6; }
    if (flags & kDpAwdlAddress) { if (!v.addr(off, nullptr)) return kRxTooShort; off += 6; }
    return kRxOk;
}
inline int handleVersionTlv(Peer &src, Reader v) { return (v.u8(0, &src.version) && v.u8(1, &src.devclass)) ? kRxOk : kRxTooShort; }
inline int handleTlv(Peer &src, uint8_t type, Reader v, State &s, uint64_t now, RxEvents *ev) {
    switch (type) {
        case kTlvSyncParams: return handleSyncParamsTlv(src, v, s, now, ev);
        case kTlvChanSeq: return handleChanSeqTlv(src, v, s);
        case kTlvElectionParams: return handleElectionParamsTlv(src, v);
        case kTlvElectionParamsV2: return handleElectionParamsV2Tlv(src, v);
        case kTlvArpa: return handleArpaTlv(src, v);
        case kTlvDataPathState: return handleDataPathStateTlv(src, v);
        case kTlvVersion: return handleVersionTlv(src, v);
        default: return kRxIgnore;
    }
}
// Returns the AWDL action subtype (PSF/MIF) or -1. `body` starts at the action category byte.
inline int parseActionHeader(const uint8_t *body, size_t len) {
    if (len < kActionHeaderLen) return -1;
    bool valid = body[0] == kVendorSpecific && !memcmp(body + 1, kAwdlOui, 3) && body[4] == kAwdlType && body[5] == version(1, 0);
    if (valid && (body[6] == kActionPSF || body[6] == kActionMIF)) return body[6];
    return -1;
}
inline int rxAction(const uint8_t *body, size_t len, int8_t rssi, uint64_t now, const Addr &src, State &s, RxEvents *ev) {
    int subtype = parseActionHeader(body, len);
    if (subtype < 0) return kRxIgnore;
    Reader f(body + kActionHeaderLen, len - kActionHeaderLen);
    if (s.filterRssi) {
        const Peer *known = s.peers.find(src);
        if ((known && rssi < s.rssiThreshold + s.rssiGrace) || (!known && rssi < s.rssiThreshold)) return kRxIgnoreRssi;
    }
    s.stats.rxAction++;
    Peer *peer; bool becameValid;
    if (s.peers.add(src, now, &peer, &becameValid) < 0) return kRxPeersFull;
    peer->rssi = rssi;
    if (becameValid && ev) ev->peerAdded(*peer);
    uint8_t type; uint16_t tlen; const uint8_t *val;
    while (f.len > 0 && f.tlv(0, &type, &tlen, &val)) {
        int r = handleTlv(*peer, type, Reader(val, tlen), s, now, ev);
        if (ev) ev->tlv(*peer, type, val, tlen);
        if (r < 0) return kRxUnexpectedFormat;
        f.strip(size_t(tlen) + 3);
    }
    if (f.len > 0) return kRxUnexpectedFormat;
    if (subtype == kActionMIF) peer->sentMif = true;
    s.peers.add(src, now, &peer, &becameValid);
    if (becameValid && ev) ev->peerAdded(*peer);
    return kRxOk;
}
inline bool validLlcHeader(Reader f) {
    uint8_t dsap, ssap, ctl; uint16_t pid;
    if (!f.u8(0, &dsap) || !f.u8(1, &ssap) || !f.u8(2, &ctl) || !f.be16(6, &pid)) return false;
    return dsap == 0xaa && ssap == 0xaa && ctl == 0x03 && pid == kLlcProtocolId;
}
// Converts one AWDL MSDU (LLC/AWDL/payload) to an Ethernet frame delivered through ev->data.
inline int rxData(Reader f, const Addr &src, const Addr &dst, State &s, RxEvents *ev) {
    s.stats.rxData++;
    if (!s.peers.find(src)) return kRxIgnorePeer;
    if (!validLlcHeader(f)) return kRxUnexpectedFormat;
    f.strip(8);
    if (f.len < 8) return kRxTooShort;
    uint16_t etherType = get16be(f.data + 6); f.strip(8);
    if (f.len + 14 > kMaxEthernet) return kRxUnexpectedFormat;
    uint8_t eth[kMaxEthernet]; memcpy(eth, dst.b, 6); memcpy(eth + 6, src.b, 6); put16be(eth + 12, etherType); memcpy(eth + 14, f.data, f.len);
    if (ev) ev->data(eth, f.len + 14, src, dst);
    return kRxOk;
}
inline int rxDataAmsdu(Reader f, State &s, RxEvents *ev) {
    while (f.len > 0) {
        Addr dstA, srcA; uint16_t lenA;
        if (!f.addr(0, &dstA) || !f.addr(6, &srcA) || !f.be16(12, &lenA) || !f.strip(14)) return kRxTooShort;
        if (lenA > f.len) return kRxTooShort;
        int err = rxData(Reader(f.data, lenA), srcA, dstA, s, ev);
        if (err < 0) return err;
        f.strip(lenA);
        if (f.len > 0 && !f.strip((4 - ((14 + lenA) % 4)) % 4)) return kRxTooShort;
    }
    return kRxOk;
}
// A plain 802.11 frame (no radiotap, no FCS). Action frames feed the protocol; data frames
// with the AWDL encapsulation are delivered as Ethernet frames.
inline int rx(const uint8_t *frame, size_t len, int8_t rssi, uint64_t now, State &s, RxEvents *ev) {
    if (len < 24) return kRxTooShort;
    uint16_t fc = get16le(frame); Addr to = Addr::of(frame + 4), from = Addr::of(frame + 10);
    if (from == s.self) return kRxIgnoreFromSelf;
    Reader f(frame + 24, len - 24);
    switch (fc & 0x00fc) {
        case kFcMgmtAction: return rxAction(f.data, f.len, rssi, now, from, s, ev);
        case kFcQosData: {
            uint16_t qos;
            if (!f.le16(0, &qos)) return kRxTooShort;
            f.strip(2);
            if (qos & kQosAmsduPresent) return rxDataAmsdu(f, s, ev);
            return rxData(f, from, to, s, ev);
        }
        case kFcData: return rxData(f, from, to, s, ev);
        default: return kRxUnexpectedType;
    }
}

// ---------------------------------------------------------------- transmit
struct Writer {
    uint8_t *p; size_t cap, len; bool overflow;
    Writer(uint8_t *b, size_t c) : p(b), cap(c), len(0), overflow(false) {}
    uint8_t *reserve(size_t n) {
        if (n > cap - len) { overflow = true; return nullptr; }
        uint8_t *r = p + len; len += n; return r;
    }
    void u8(uint8_t v) { if (uint8_t *r = reserve(1)) *r = v; }
    void le16(uint16_t v) { if (uint8_t *r = reserve(2)) put16le(r, v); }
    void be16(uint16_t v) { if (uint8_t *r = reserve(2)) put16be(r, v); }
    void le32(uint32_t v) { if (uint8_t *r = reserve(4)) put32le(r, v); }
    void bytes(const void *b, size_t n) { if (uint8_t *r = reserve(n)) memcpy(r, b, n); }
    void addr(const Addr &a) { bytes(a.b, 6); }
    void zeros(size_t n) { if (uint8_t *r = reserve(n)) memset(r, 0, n); }
};
inline void initAwdlHeader(Writer &w, const Addr &src, const Addr &dst, Ieee80211State &st, uint16_t fc) {
    w.le16(fc); w.le16(0); w.addr(dst); w.addr(src); w.bytes(kAwdlBssid, 6); w.le16(uint16_t(st.next() << 4));
}
inline void initAction(Writer &w, ActionType type, uint32_t steadyTime) {
    w.u8(kVendorSpecific); w.bytes(kAwdlOui, 3); w.u8(kAwdlType); w.u8(version(1, 0)); w.u8(type); w.u8(0); w.le32(steadyTime); w.le32(steadyTime);
}
inline void initChanSeq(Writer &w, const State &s) {
    int encLen = chanEncodingSize(s.channel.enc);
    w.u8(kChanSeqLength - 1); w.u8(s.channel.enc); w.u8(0); w.u8(3); w.le16(0xffff);
    for (int i = 0; i < kChanSeqLength; ++i) w.bytes(s.channel.sequence[i].val, size_t(encLen));
}
// TLV with a length field patched after the body is written.
struct TlvScope { Writer &w; size_t lenAt; TlvScope(Writer &ww, uint8_t type) : w(ww), lenAt(ww.len + 1) { w.u8(type); w.le16(0); }
    void close() { if (!w.overflow) put16le(w.p + lenAt, uint16_t(w.len - lenAt - 2)); }
};
inline void initSyncParamsTlv(Writer &w, const State &s, uint64_t now) {
    TlvScope t(w, kTlvSyncParams);
    uint16_t awPeriod = s.sync.awPeriod, txDown = syncNextAwTu(now, s.sync), nextAwSeq = syncCurrentAw(now, s.sync);
    w.u8(chanNum(s.channel.current, s.channel.enc)); // next_aw_channel
    w.le16(txDown);                                   // tx_down_counter
    w.u8(chanNum(s.channel.master, s.channel.enc));   // master_channel
    w.u8(0);                                          // guard_time
    w.le16(awPeriod); w.le16(s.psfInterval); w.le16(0x1800); w.le16(awPeriod); w.le16(awPeriod);
    uint32_t elapsed = uint32_t(awPeriod) * s.sync.presenceMode - txDown;
    w.le16(awPeriod < elapsed ? 0 : uint16_t(awPeriod - elapsed)); // remaining_aw_length
    w.u8(uint8_t(s.sync.presenceMode - 1)); w.u8(uint8_t(s.sync.presenceMode - 1)); w.u8(uint8_t(s.sync.presenceMode - 1)); w.u8(uint8_t(s.sync.presenceMode - 1));
    w.addr(s.election.masterAddr); w.u8(s.sync.presenceMode); w.u8(0); w.le16(nextAwSeq); w.le16(nextAwSeq);
    initChanSeq(w, s); w.zeros(2); t.close();
}
inline void initChanSeqTlv(Writer &w, const State &s) { TlvScope t(w, kTlvChanSeq); initChanSeq(w, s); w.zeros(3); t.close(); }
inline void initElectionParamsTlv(Writer &w, const State &s) {
    TlvScope t(w, kTlvElectionParams); w.u8(0); w.le16(0); w.u8(uint8_t(s.election.height)); w.u8(0); w.addr(s.election.masterAddr);
    w.le32(s.election.masterMetric); w.le32(s.election.selfMetric); w.zeros(2); t.close();
}
inline void initElectionParamsV2Tlv(Writer &w, const State &s) {
    TlvScope t(w, kTlvElectionParamsV2); w.addr(s.election.masterAddr); w.addr(s.election.syncAddr); w.le32(s.election.masterCounter);
    w.le32(s.election.height); w.le32(s.election.masterMetric); w.le32(s.election.selfMetric); w.le32(0); w.le32(0); w.le32(s.election.selfCounter); t.close();
}
inline void initServiceParamsTlv(Writer &w) { TlvScope t(w, kTlvServiceParams); w.zeros(3); w.le16(0); w.le32(0); t.close(); }
inline void initHtCapabilitiesTlv(Writer &w) { TlvScope t(w, kTlvHtCapabilities); w.le16(0); w.le16(0x11ce); w.u8(0x1b); w.u8(0xff); w.le16(0); t.close(); }
inline void initDataPathStateTlv(Writer &w, const State &s) {
    TlvScope t(w, kTlvDataPathState); w.le16(0x8f24); w.u8('X'); w.u8('0'); w.u8(0);
    uint8_t master = chanNum(s.channel.master, kChanEncOpclass);
    w.le16(master == 6 ? 0x0001 : master == 44 ? 0x0002 : 0x0004); w.addr(s.self); w.le16(0); t.close();
}
inline void initArpaTlv(Writer &w, const State &s) {
    TlvScope t(w, kTlvArpa); size_t n = strlen(s.name); w.u8(3); w.u8(uint8_t(n)); w.bytes(s.name, n); w.be16(kDnsShortLocal); t.close();
}
inline void initVersionTlv(Writer &w, const State &s) { TlvScope t(w, kTlvVersion); w.u8(s.version); w.u8(s.devClass); t.close(); }
// A complete PSF or MIF: 802.11 action frame, no radiotap, no FCS. Returns the length or 0 if it does not fit.
inline size_t buildActionFrame(uint8_t *buf, size_t cap, State &s, Ieee80211State &st, ActionType type, uint64_t now) {
    Writer w(buf, cap);
    initAwdlHeader(w, s.self, s.dst, st, kFcMgmtAction); initAction(w, type, uint32_t(now));
    initSyncParamsTlv(w, s, now); initElectionParamsTlv(w, s); initChanSeqTlv(w, s); initElectionParamsV2Tlv(w, s); initServiceParamsTlv(w);
    if (type == kActionMIF) { initHtCapabilitiesTlv(w); initArpaTlv(w, s); }
    initDataPathStateTlv(w, s); initVersionTlv(w, s);
    return w.overflow ? 0 : w.len;
}
// A complete AWDL data frame carrying one Ethernet payload (without its 14-byte header).
inline size_t buildDataFrame(uint8_t *buf, size_t cap, const Addr &src, const Addr &dst, uint16_t etherType, const uint8_t *payload, size_t plen, State &s, Ieee80211State &st) {
    Writer w(buf, cap);
    initAwdlHeader(w, src, dst, st, kFcData);
    w.u8(0xaa); w.u8(0xaa); w.u8(0x03); w.bytes(kAwdlOui, 3); w.be16(kLlcProtocolId);         // LLC/SNAP
    w.le16(kDataHead); w.le16(s.nextSequenceNumber()); w.le16(0); w.be16(etherType);          // AWDL data header
    w.bytes(payload, plen);
    return w.overflow ? 0 : w.len;
}

// ---------------------------------------------------------------- engine
// What the engine needs from the radio and the host stack.
struct Sink : RxEvents {
    virtual void setChannel(uint8_t chan) = 0;                               // tune the AWDL radio path
    virtual bool transmit(const uint8_t *frame, size_t len, bool action) = 0; // 802.11 frame on the current channel
};
// A fixed queue of Ethernet frames waiting for a transmit window.
struct TxQueue {
    static constexpr int kSlots = 16; struct Slot { uint16_t len; uint8_t data[kMaxEthernet]; } slots[kSlots]; int head, count;
    void init() { head = 0; count = 0; }
    bool empty() const { return count == 0; } bool full() const { return count == kSlots; }
    bool put(const uint8_t *d, size_t n) {
        if (full() || n > kMaxEthernet || n < 14) return false;
        Slot &s = slots[(head + count) % kSlots]; s.len = uint16_t(n); memcpy(s.data, d, n); ++count; return true;
    }
    const Slot *peek() const { return count ? &slots[head] : nullptr; }
    void pop() { if (count) { head = (head + 1) % kSlots; --count; } }
};
// Drives OWL's timers (channel switch at every AW, PSF every psf_interval, MIF mid-EAW, peer
// clean-up + election every second, unicast/multicast data windows) from tick(now).
class Engine {
public:
    State state; Ieee80211State ieee80211; TxQueue unicast, multicast; Sink *sink = nullptr;
    uint64_t nextChannelSwitch = 0, nextPsf = 0, nextMif = 0, nextClean = 0, nextUnicast = 0, nextMulticast = 0; bool running = false;
    uint8_t frame[kMaxFrame];

    void start(const char *hostname, const Addr &self, Chan masterChan, uint64_t now, Sink *s) {
        stateInit(state, hostname, self, masterChan, now); ieee80211.sequenceNumber = 0; unicast.init(); multicast.init(); sink = s;
        nextChannelSwitch = now; nextPsf = now + tuToUs(state.psfInterval); nextMif = now; nextClean = now + state.peers.cleanInterval;
        nextUnicast = nextMulticast = 0; running = true;
    }
    void stop() { running = false; }
    // Receive one 802.11 frame from the radio (action frames and AWDL data frames).
    int receive(const uint8_t *f, size_t len, int8_t rssi, uint64_t now) { if (!running) return kRxIgnore; return rx(f, len, rssi, now, state, sink); }
    // Queue an Ethernet frame from the host stack for AWDL transmission.
    bool send(const uint8_t *eth, size_t len, uint64_t now) {
        if (!running || len < 14) return false;
        bool mcast = eth[0] & 1;
        bool ok = mcast ? multicast.put(eth, len) : unicast.put(eth, len);
        if (ok) {
            if (mcast) nextMulticast = now; else nextUnicast = now;
        }
        return ok;
    }
    // Runs everything that is due and returns the time of the next due action.
    uint64_t tick(uint64_t now) {
        if (!running) return ~0ull;
        if (now >= nextChannelSwitch) switchChannel(now);
        if (now >= nextClean) cleanPeers(now);
        if (now >= nextPsf) { sendAction(kActionPSF, now); while (nextPsf <= now) nextPsf += tuToUs(state.psfInterval); }
        if (now >= nextMif) sendMif(now);
        if (!unicast.empty() && now >= nextUnicast) sendUnicast(now);
        if (!multicast.empty() && now >= nextMulticast) sendMulticast(now);
        uint64_t next = nextChannelSwitch;
        if (nextClean < next) next = nextClean;
        if (nextPsf < next) next = nextPsf;
        if (nextMif < next) next = nextMif;
        if (!unicast.empty() && nextUnicast < next) next = nextUnicast;
        if (!multicast.empty() && nextMulticast < next) next = nextMulticast;
        return next;
    }
    uint8_t currentChannel() const { return chanNum(state.channel.current, state.channel.enc); }

private:
    void switchChannel(uint64_t now) {
        int slot = syncCurrentEaw(now, state.sync) % kChanSeqLength; Chan c = state.channel.sequence[slot];
        uint8_t newNum = chanNum(c, state.channel.enc), oldNum = currentChannel();
        if (newNum && newNum != oldNum) { if (sink) sink->setChannel(newNum); state.channel.current = c; }
        nextChannelSwitch = now + syncNextAwUs(now, state.sync);
    }
    void cleanPeers(uint64_t now) {
        uint64_t cutoff = now - state.peers.timeout;
        for (auto &p : state.peers.peers) if (p.used && p.lastUpdate < cutoff) { if (p.valid && sink) sink->peerRemoved(p); p.used = false; }
        electionRun(state.election, state.peers);
        state.psfInterval = state.election.height ? kPsfIntervalSlaveTu : kPsfIntervalMasterTu;
        nextClean = now + state.peers.cleanInterval;
    }
    void sendAction(ActionType type, uint64_t now) {
        size_t n = buildActionFrame(frame, sizeof(frame), state, ieee80211, type, now);
        if (n && sink && sink->transmit(frame, n, true)) state.stats.txAction++;
    }
    void sendMif(uint64_t now) {
        uint64_t nextAw = syncNextAwUs(now, state.sync), eawLen = uint64_t(state.sync.presenceMode) * state.sync.awPeriod;
        if (currentChannel() > 0) sendAction(kActionMIF, now);
        nextMif = now + nextAw + tuToUs(eawLen / 2);
    }
    bool sendData(const uint8_t *eth, size_t len) {
        Addr dst = Addr::of(eth), src = Addr::of(eth + 6); uint16_t et = get16be(eth + 12);
        size_t n = buildDataFrame(frame, sizeof(frame), src, dst, et, eth + 14, len - 14, state, ieee80211);
        if (!n || !sink) return false;
        state.stats.txData++;
        return sink->transmit(frame, n, false);
    }
    void sendUnicast(uint64_t now) {
        const TxQueue::Slot *s; int64_t in = 0;
        while ((s = unicast.peek())) {
            Addr dst = Addr::of(s->data);
            if (dst == state.self) { if (sink) sink->data(s->data, s->len, Addr::of(s->data + 6), dst); unicast.pop(); continue; }
            const Peer *peer = state.peers.find(dst);
            if (!peer) { unicast.pop(); continue; } // frames to non-peers are dropped
            in = canSendUnicastIn(state, *peer, now, kUnicastGuardTu);
            if (in == 0) { sendData(s->data, s->len); state.stats.txDataUnicast++; unicast.pop(); continue; }
            if (in < 0) in = -in + int64_t(tuToUs(kUnicastGuardTu));
            break;
        }
        nextUnicast = unicast.empty() ? 0 : now + uint64_t(in);
    }
    void sendMulticast(uint64_t now) {
        int64_t in = canSendIn(state, now, kMulticastGuardTu);
        if (isMulticastEaw(state, now) && in == 0) {
            if (const TxQueue::Slot *s = multicast.peek()) { sendData(s->data, s->len); state.stats.txDataMulticast++; multicast.pop(); }
            in = multicast.empty() ? 0 : int64_t(tuToUs(1));
        } else if (in == 0) in = int64_t(tuToUs(64));
        else if (in < 0) in = -in + int64_t(tuToUs(kMulticastGuardTu));
        nextMulticast = multicast.empty() ? 0 : now + uint64_t(in);
    }
};

