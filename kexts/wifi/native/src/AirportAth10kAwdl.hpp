// AWDL (Apple Wireless Direct Link) protocol engine for AirportAth10k.
//
// A port of the platform-independent part of SEEMOO's Open Wireless Link (OWL,
// https://github.com/seemoo-lab/owl, GPL-3.0, Milan Stute et al.; commit 0ee3263) to a
// header-only, allocation-free C++ unit that can live in a kext: frame layout (action
// frames with the AWDL TLVs, data frames with the LLC/AWDL encapsulation), the
// synchronisation and election state machines, the channel sequence, the peer table and
// the transmit schedule (availability windows and guard times). The protocol facts come
// from Stute, Kreitschmann, Hollick, "One Billion Apples' Secret Sauce" (MobiCom '18).
//
// Differences from OWL, all deliberate:
//  - no malloc (fixed peer table, fixed queues), no double (all times are integer
//    microseconds), no libc beyond memcpy/memcmp/memset/strlen,
//  - frames are plain 802.11 frames (no radiotap): the kext gets management frames from
//    the firmware without a radiotap header and hands 802.11 frames to it for transmit,
//  - a peer's channel sequence is decoded with the encoding the peer announced (OWL decodes
//    it with the local encoding),
//  - the engine is driven by tick(now) and receive(); it never reads a clock or a device.
//
// Wire-format compatibility with OWL is pinned by native/tests/test_native_awdl.cpp against
// vectors generated by OWL's own C code (native/tests/awdl_vectors.inc).
#pragma once
#include <stdint.h>
